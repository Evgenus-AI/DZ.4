using System;

class Program
{
    // out = выходной параметр. Метод ОБЯЗАН присвоить ему значение на всех путях выполнения,
    // иначе компилятор выдаст ошибку. Инициализировать переменную до вызова не нужно.
    // Возвращаемый bool говорит об успехе, а само число уходит через out.
    static bool TryFactorial(int n, out long result)
    {
        // Факториал определён только для n >= 0. Отрицательное n — это ошибка вызывающего кода,
        // а не «переполнение», поэтому бросаем исключение, а не возвращаем false.
        if (n < 0)
            throw new ArgumentOutOfRangeException(nameof(n), "Факториал определён только для n >= 0");

        result = 1; // 0! = 1 и 1! = 1. Присваиваем сразу, чтобы out был задан в любом случае.

        try
        {
            // По умолчанию C# при переполнении целых молча «заворачивает» число (получится мусор).
            // Блок checked включает проверку: при переполнении будет брошен OverflowException.
            checked
            {
                for (int i = 2; i <= n; i++)
                {
                    result *= i; // здесь может случиться переполнение long
                }
            }

            return true; // дошли до конца без исключения
        }
        catch (OverflowException)
        {
            result = 0;      // результат недостоверен, обнуляем (out всё равно должен быть задан)
            return false;
        }
    }

    static void Main()
    {
        // 20! = 2432902008176640000 — самое большое, что влезает в long.
        // 21! уже больше long.MaxValue (~9.22 * 10^18), значит будет переполнение.
        int[] tests = { 0, 1, 5, 10, 20, 21, 25 };

        foreach (int n in tests)
        {
            // out long value — объявляем переменную прямо в месте вызова
            if (TryFactorial(n, out long value))
                Console.WriteLine($"{n}! = {value}");
            else
                Console.WriteLine($"{n}! — переполнение, результат не поместился в long");
        }
    }
}
